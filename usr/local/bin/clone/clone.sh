# return: 0 on success else the error code of the command that failed
trap_signals() {
    local -i err
    
    # register signal hander to mask hibernation if another clone process has
    # completed or was interrupted (signal USR1)
    trap "mask_hibernation 1" USR1 &> /dev/null
    ((err=$?))
    
    if (( ! err )); then
        # register signal hander to clean up and exit if cancel signal is
        # received
        trap "cleanup 1" $CANCEL_SIGNALS &> /dev/null
        ((err=$?))
    fi
    
    (( err )) && cecho -e "\n${RED}Error while trapping signals, error code: $err. Exiting."

    return $err
}

# display list of detected disks and cloning usage
# return: 0 on success else 1
usage() {
    clear

    # return if text files needed by script don't exist
    if ! files_exist LOOP; then return 1; fi
    
    # read file that contains files and/or directories to be excluded from or
    # included in cloning and save them
    local -i num
    local -a filters=()

    exec {num}< "$FILTERS" # open filters file
    while read -r -u $num; do
        # remove leading & trailing spaces and tabs
        REPLY=$(echo "$REPLY" | sed -e 's/^[[:blank:]]*//' -e 's/[[:blank:]]*$//')
        (( ! ${#REPLY} ))  && continue  # skip empty lines

        REPLY=$(expr "$REPLY" : "\(^[^#].*$\)") # get lines that are not comments
        (( $? )) && continue # skip comments

        # remove redundant /, * and space
        while [[ "$REPLY" =~ ('//'|'**'|[[:blank:]][[:blank:]][[:blank:]]) ]]; do 
            REPLY="${REPLY//'//'/'/'}"
            REPLY="${REPLY//'**'/'*'}"
            REPLY="${REPLY//[[:blank:]][[:blank:]][[:blank:]]/'  '}" # replace 3 with 2
        done    
        
        filters+=("$REPLY") # save entry excluded from or included in cloning
    done
    exec {num}<&- # close the filters file

    cat << intro_msg
This script clones a disk to another. To run it just type in its name and press
enter. Then, you will be asked for source and destination disks. Source and
destination need not be the same size as long as all source data fits on
destination. Also, the directories and/or files contained in the
$YELLOW'$FILTERS'$OFF
file will ${YELLOW}NOT$OFF be cloned. Here they are:

intro_msg

    for num in "${!filters[@]}"; do
        cecho "$CYAN${filters[num]}"
    done
    echo
    
    cat << intro_msg
The script will work only on a linux machine using the GRUB 2 bootloader,
systemd and with source disks that have partitions with UUIDs. It will NOT work
with disks that have Logical Volume Management (LVM).

Here is a list of available disks on your system:
=================================================
intro_msg

    g_parted_data=()
    
    # get disk and partition data in human readable format
    readarray -t g_parted_data < <(parted --script --list 2> /dev/null)

    ((disk_cnt=0))
    local line

    # iterate over disk and partition data
    for line in "${g_parted_data[@]}"; do
        # the output of 'parted' command is something like:
        #
        # Model: ATA TOSHIBA MQ01ABD1 (scsi)
        # Disk /dev/sda: 1000GB

        if [[ "$line" =~ ^"Model: " ]]; then
            (( disk_cnt > 0 )) && echo # seperate one disk output from another
            ((++disk_cnt))
            echo "$disk_cnt.  $line" # display disk model (see comment above)
        elif [[ "$line" =~ ^"Disk /dev/" ]]; then
            echo "    $line" # display disk size (see comment above)
        fi
    done

    cat << intro_msg
=================================================

Cloning parameters have to be entered in the following order:
    <source disk number> <destination disk number>

    Examples: 1 2
          or  2 1

${YELLOW}Before proceeding close all programs on all user accounts and exit all user
accounts but this one.${OFF}

intro_msg
}

# Get and validate cloning options.
# return: 0 on success else 1
user_input() {
    OPTIONS=()
    echo -en "Enter cloning parameters (see examples above or Ctrl-C to perform"\
             "cleanup and\nget exit message): "
    read -r -a OPTIONS # read cloning options into array

    START_DATE=$(date) # timestamp will be used to calculate the clone run time

    # return if text files needed by script don't exist
    if ! files_exist LOOP; then return 1; fi

    local -a parted_data # disk data retrieved from 'parted' command

    # get parted data again
    readarray -t parted_data < <(parted --script --list 2> /dev/null)

    # compare current parted data with original
    if [[ "${parted_data[*]}" != "${g_parted_data[*]}" ]]; then
        prompt LOOP "\nThe disk configuration has changed.\n"
        return $?
    fi

    local -i i

    # convert to lowercase and remove whitespace
    for i in "${!OPTIONS[@]}"; do
        OPTIONS[i]="${OPTIONS[i],,}"
        OPTIONS[i]="${OPTIONS[i]//[[:blank:]]/}"
    done

    cat << validate_params


Proceeding...

Validating parameters...
validate_params

    # validate cloning options and if error, prompt the user to try again
    if (( ${#OPTIONS[@]} != 2 )); then
        local msg="\nExactly two cloning parameters are needed. See description"
        
        msg+=" and examples above.\n"
        prompt LOOP "$msg"
    elif (( OPTIONS[0] > disk_cnt || OPTIONS[0] < 1 )); then
        prompt LOOP "\nSource disk has to be an option within [1, $disk_cnt].\n"
    elif (( OPTIONS[1] > disk_cnt || OPTIONS[1] < 1 )); then
        prompt LOOP "\nDestination disk has to be an option within [1, $disk_cnt].\n"
    elif (( OPTIONS[0] == OPTIONS[1] )); then
        prompt LOOP "\nSource and destination disks can't be the same.\n"
    else
        ((LOOP=0))
        echo 
    fi
}

# initialize the clone session
# return: 0 on success else the error code of the command that failed
init() {
    echo "Initializing..."

    OPTIONS_S=$(expr "$LOGDIR" : "^.\+\([0-9]\+_[0-9]\+\)$")

    # in case this is not the first attempt, e.g. the user entered wrong data,
    # remove any cloning options from log dir
    LOGDIR="${LOGDIR//$OPTIONS_S/}"

    local -i fd

    # create lock dir and set its access rights
    mkdir -p "$LCKDIR" && chmod go+=rx "$LCKDIR"
    ((fd=$?))
    if (( fd )); then
        cechot "The lock directory, $YELLOW'$LCKDIR'$RED, could not be created " \
               "or set to read & execute. Exiting."
        return $fd
    fi

    # critical section
    (
        if ! flock $fd; then exit $?; fi

        # if there's no clone process other than this one then delete all log, 
        # error and command files from the previous run
        if [[ ! -s "$LCKFILE" ]]; then
            echo -e "\tRemoving old clone log directories from $LOGDIR ..."

            rm -rf "$LOGDIR"/*
        fi
                
    ) {fd}>> "$LCKFILE"
    ((fd=$?))
    if (( fd )); then 
        cechot "The lock file, $YELLOW'$LCKFILE'$RED, could not be created. " \
               "Exiting."
        return $fd
    fi

    # create log dir and set access rights
    mkdir -p "$LOGDIR" && chmod go+=rx "$LOGDIR"
    ((fd=$?))
    if (( fd )); then 
        cechot "The log directory, $YELLOW'$LOGDIR'$RED, could not be created " \
               "or set to read & execute. Exiting."
        return $fd
    fi

    # complete the filename of log dir
    OPTIONS_S="${OPTIONS[0]}_${OPTIONS[1]}"
    if [[ "${LOGDIR: -1}" == "/" ]]; then
        LOGDIR+="$OPTIONS_S"
    else
        LOGDIR+="/$OPTIONS_S"
    fi
    
    # set complete filename for log, error and command files
    LOGFILE="$LOGDIR/log"
    ERRFILE="$LOGDIR/errors"
    CMDFILE="$LOGDIR/commands"

    # create log dir and set access rights
    mkdir -p "$LOGDIR" &&
    chmod go+=rx "$LOGDIR" && 
    touch "$LOGFILE" "$ERRFILE" "$CMDFILE" &&
    chmod go=+r "$LOGFILE" "$ERRFILE" "$CMDFILE"
    ((fd=$?))
    if (( fd )); then
        cechot "The log directory, $YELLOW'$LOGDIR'$RED, could not be created " \
               "or set to read & execute or one of $YELLOW'$LOGFILE'$RED, " \
               "$YELLOW'$ERRFILE'$RED or $YELLOW'$CMDFILE'$RED, could not be " \
               "created or set to read. Exiting."
        return $fd
    fi

    # critical section
    (
        if ! flock $fd >> "$LOGFILE" 2>> "$ERRFILE"; then exit 1; fi

        # exit if src or dst disks are currently used as destinations by
        # other clone processes
        for option in "${OPTIONS[@]}"; do
            clone_process=$(grep -E "^[0-9]+_[0-9]+_$option$" "$LCKFILE")
            if (( $? == 0 )); then
                cat << error_msg
${RED}A clone process with pid $YELLOW$(expr "$clone_process" : "^\([0-9]\+\)")
${RED}is currently running and using ${YELLOW}disk $option$RED as a destination.
$OFF
error_msg
                exit 1
            fi
        done
        
        declare -i err
        
        chmod go=+r "$LCKFILE" &&  # set access rights of lock file
        echo "$$_$OPTIONS_S" >&$fd # add entry to lock file
        ((err=$?))

        echo
        if ((err)); then
            cechot "The lock file, $YELLOW'$LCKFILE'$RED, could not be set to " \
                   "read or appended to. Exiting." | tee -a "$ERRFILE"
            exit 2
        fi
    ) {fd}>> "$LCKFILE" # open for append

    if (( $? == 1 )); then prompt LOOP; fi
}

# save src & dst disk data based on user input
# return: 0 on success else 1
populate_arrays() {
    echo "Creating internal data structures..."

    local -a parted_data # disk data retrieved from 'parted' command

    # get disk and partition data for all disks in machine parsable format
    readarray -t parted_data < <(parted -mls 2>> "$ERRFILE")

    local line
    local -i disk_num=0 # disk number used as index in associative array

    # iterate over disk data to get disk names
    disks_info=()
    for line in "${parted_data[@]}"; do
        if [[ "$line" =~ ^/dev/ ]]; then
            ((++disk_num))

            # if the disk is src or dst save disk name in associative array of disks
            (( disk_num == OPTIONS[0] || disk_num == OPTIONS[1] )) && 
                disks_info[$disk_num]=$(field "$line" $DNAME)
        fi
    done

    srcdisk="${disks_info[${OPTIONS[0]}]}" # extract src disk name
    dstdisk="${disks_info[${OPTIONS[1]}]}" # extract dst disk name

    # device names that end in a number have their partitions prefixed by the
    # following literal 
    local PTN_PREFIX="p"

    if [[ "$srcdisk" =~ $DISK_SUFFIX ]]; then SP="$PTN_PREFIX"; else SP=""; fi
    if [[ "$dstdisk" =~ $DISK_SUFFIX ]]; then DP="$PTN_PREFIX"; else DP=""; fi
    
    local srcptn

    # if script is running on dst disk exit with error
    srcptn=$(df -ak --sync --output=source "$SCRIPTDIR" | tail -1)
    if [[ "$srcptn" =~ $dstdisk$DP ]]; then
        prompt LOOP "\nYou can't run the clone script on the destination disk.\n"
        return $?
    fi

    local msg
    
    # The dst disk can't be the disk that was used to boot the system, as this
    # would destroy the system. This extreme case is possible if:
    # 1. the clone directory is copied to a disk that was not used to boot the
    #    system
    # 2. the clone script is executed on that disk and the disk that is selected
    #    as destination is the disk that was used to boot the system 
    if [[ "$BOOTPTN" =~ $dstdisk$DP ]]; then
        msg="\nThe destination disk can't be the disk that was used to boot the"
        msg+=" system.\n"
        prompt LOOP "$msg"
        return $?
    fi
    
    local DST_DISK_NAME
    DST_DISK_NAME=$(expr "$(lsblk -dP -o NAME "$dstdisk")" : "^NAME=\"\(.*\)\"$")

    # the following algorithm was found at
    # http://people.redhat.com/msnitzer/docs/io-limits.txt
    # at the bottom of the web page

    ((DST_ALIGN=MIBIBYTE))

    # get alignment offset
    ((start=$(cat /sys/block/"$DST_DISK_NAME"/alignment_offset)))

    # if no alignment offset then get optimal_io_size
    if (( ! start )); then
        ((start=$(cat /sys/block/"$DST_DISK_NAME"/queue/optimal_io_size)))
        (( start )) && ((DST_ALIGN=start))
    fi

    # if no optimal_io_size then get minimum_io_size
    if (( ! start )); then
        start=$(cat /sys/block/"$DST_DISK_NAME"/queue/minimum_io_size)

        # if minimum_io_size exists return if not power of 2
        if (( start )); then
            if (( $(bc -l <<< "x=l($start)/l(2); scale=0; 2^((x+0.5)/1)") != start ))
            then
                msg="\nThe minimum_io_size is not a power of two: "
                msg+="$YELLOW$start$RED. Exiting."
                stack "$msg"
                return $?
            else
                # if minimum_io_size is a power of 2 set the alignment to 1MiB
                ((start=MIBIBYTE))
            fi
        else
            msg="\nNo alignment boundary was found for disk $YELLOW$dstdisk$RED. "
            msg+="Exiting."
            stack "$msg"
            return $?
        fi
    fi

    local -i page_size
    local -a page_sizes

    # get page size
    readarray -t page_sizes < <(getconf -a 2>> "$ERRFILE" | grep -iE "pagesize|page_size")
    
    # save page size
    for line in "${page_sizes[@]}"; do
        ((page_size=${line/+([^0-9])}))
        (( page_size )) && break
    done

    # if page size is 0, exit
    if (( ! page_size )); then
        stack "\nPage size is zero. Exiting."
        return $?
    fi

    echo -e "\tGetting disk and partition data for source and destination disks..."

    partitions=()
    ((no_resize=0))
    esp_ptn_nums=(0 0)
    boot_ptn_nums=(0 0)
    bios_ptn_nums=(0 0)
    local -i ptn_num
    local -i ptn_cnt
    local -i startb
    local -i end
    local -i size
    local fstype
    local name  # partition name, if any
    local flags # partition flags
    
    # iterate over all disks to get extra data like disk size and partition data
    # THE ORDER OF DISK NUMBERS IS IMPORTANT. SOURCE DISK NUMBER MUST BE LAST.
    # THIS HELPS TO FACILITATE PROCESSING LATER ON.
    for disk_num in {${OPTIONS[1]},${OPTIONS[0]}}; do
        # The output of the command below is something like
        #
        # BYT;
        # /dev/sda:1000204886016B:scsi:512:4096:gpt:ATA TOSHIBA MQ01ABD1:;
        # 1:1048576B:269484031B:268435456B:fat16:efiboot:boot, esp;
        # 2:269484032B:998024151039B:997754667008B:ext4:root:;
        # 3:998024151040B:1000204140543B:2179989504B:linux-swap(v1):swap:;

        # get disk and partition data for a single disk (unit is bytes)
        readarray -t parted_data \
            < <(parted -ms "${disks_info[$disk_num]}" unit $UNIT print 2>> "$ERRFILE")

        ((ptn_num=0))
        ((ptn_cnt=0))
        
        # iterate over disk data
        for line in "${parted_data[@]}"; do
            if [[ "$line" =~ ^/dev/ ]]; then # if disk get its data
                disks_info[$disk_num]+=":"
                disks_info[$disk_num]+=$(field_re "$line" $DSIZE) # size
                disks_info[$disk_num]+=":"
                
                # partition table type
                disks_info[$disk_num]+=$(field "$line" $DPTN_TBL_TYPE)
                
                # sector size in bytes of src disk
                (( disk_num == OPTIONS[0] )) && 
                    ((src_lba=$(field "$line" $DSECTOR_SIZE)))
                    
            # match the format of the first two fields (see above sample 
            # command output)
            elif [[ "$line" =~ ^[0-9]+:[0-9]+$UNIT ]]; then
                # get partition data
                ((ptn_num=$(field "$line" $PPTN_NUM)))
                ((startb=$(field_re "$line" $PSTART)))
                ((end=$(field_re "$line" $PEND)))
                ((size=$(field_re "$line" $PSIZE)))
                fstype=$(field "$line" $PFSTYPE)
                name=$(field "$line" $PNAME)
                (( ! ${#name} )) && name=primary
                flags=$(field_re "$line" $PFLAGS "\([^;]*\)")
                
                # add partition data to partitions array
                partitions+=("$disk_num:$ptn_num:$startb:$end:$size:$fstype:$name:$flags:")

                # if src disk get more data
                if (( disk_num == OPTIONS[0] )); then
                    (( ++ptn_cnt ))
                    partitions[-1]+=$ptn_cnt:

                    # add size of partition 1 start byte
                    (( ptn_cnt == 1 )) && ((no_resize+=startb))

                    # add size of esp, boot, bios and swap partitions
                    if [[ "$flags" =~ esp || "$flags" =~ boot || \
                          "$flags" =~ bios || "$fstype" =~ swap ]]; then
                        [[ ! "$flags" =~ boot ]] && ((no_resize+=size))

                        # save partition number of ESP partition
                        if [[ "$flags" =~ esp ]]; then
                            ((esp_ptn_nums[0]=ptn_num))
                            ((esp_ptn_nums[1]=ptn_cnt))
                        fi

                        # save partition number of boot (BIOS) partition
                        if [[ "$flags" =~ boot ]]; then
                            ((boot_ptn_nums[0]=ptn_num))
                            ((boot_ptn_nums[1]=ptn_cnt))
                        fi
                        
                        # save partition number of bios grub partition
                        if [[ "$flags" =~ bios ]]; then
                            ((bios_ptn_nums[0]=ptn_num))
                            ((bios_ptn_nums[1]=ptn_cnt))
                        fi
                    fi
                fi
            fi
        done

        # add size of remaining space in src partition
        if (( disk_num == OPTIONS[0] )); then
            if (( ptn_cnt > 0 )); then
                ((no_resize += $(field "${disks_info[$disk_num]}" $DSIZE) - end))
            else
                # exit if no partitions to clone
                cecho -e "\n${RED}Source disk $YELLOW$srcdisk$RED has no"\
                         "partitions to clone! Exiting." | tee -a "$ERRFILE"
                return 1
            fi
        fi
    done

    ((LOOP=0))
    readonly LOOP

    readonly OPTIONS OPTIONS_S
    readonly LOGFILE ERRFILE CMDFILE
    readonly PTN_PREFIX SP DP
    readonly DST_DISK_NAME
    readonly START_DATE

    # finalize numbers of fields
    ((DPTN_TBL_TYPE=3))
    ((PPTN_NUM+=1))
    ((PSTART+=1))
    ((PEND+=1))
    ((PSIZE+=1))
    ((PFSTYPE+=1))
    ((PNAME+=1))
    ((PFLAGS+=1))
    readonly DPTN_TBL_TYPE PPTN_NUM PSTART PEND PSIZE PFSTYPE PNAME PFLAGS
    readonly DST_ALIGN

    echo -e "\tCalculating partition offset and size for source and destination disks..."

    # total amount of space that can't be resized, i.e. esp, boot, bios and 
    # swap partitions
    local -i no_resize_dst=0
    local -i i
    local ptn
    local -i alignment
    local -i prev_alignment
    local -i sector_size
    alignments=()
    
    # iterate over partitions to align their start offset and size based on
    # partition and filesystem alignment
    for i in "${!partitions[@]}"; do
        ptn="${partitions[i]}"
        
        # extract disk number to find if partition is src or dst
        ((disk_num=$(field "$ptn" $PDISK_NUM)))

        # if src partition then add aligned fields (start offset & size)
        if (( disk_num == OPTIONS[0] )); then
            ((ptn_cnt=$(field "$ptn" $PPTN_CNT))) # extract partition counter

            # add the aligned start offset of the partition as a last field
            if (( ptn_cnt > 1 )); then
                # if previous partition exists the new start offset is the sum
                # of [start offset + size] of previous partition
                partitions[i]="$ptn"
                partitions[i]+=$(( $(field "${partitions[i-1]}" $PALIGN_START) + 
                                   $(field "${partitions[i-1]}" $PALIGN_SIZE) ))
                partitions[i]+=":"
            else
                # the new start offset is the alignment of first partition
                partitions[i]="$ptn"$start:

                # update the byte counter of non-resizable bytes
                ((no_resize_dst+=start))
            fi

            fstype=$(field "$ptn" $PFSTYPE) # extract filesystem type
            flags=$(field "$ptn" $PFLAGS)   # extract partition flags
            
            # get sector size for partition
            ((sector_size=$(get_sector_size)))
            if (( sector_size == 1 )); then return $sector_size; fi
            
            # get partition alignment
            ((alignment=$(align_ptn $DST_ALIGN "$fstype" "$flags")))
            
            ((size=$(field "$ptn" $PSIZE)))         # extract partition size
            ((size=$(align_size $size $alignment))) # align partition size

            # if next partition exists
            if (( i+1 < ${#partitions[@]} )); then
                # extract next partition's filesystem type
                fstype=$(field "${partitions[i+1]}" $PFSTYPE)
                
                # extract next partition's flags
                flags=$(field "${partitions[i+1]}" $PFLAGS)
                
                # get sector size for next partition
                ((sector_size=$(get_sector_size)))
                if (( sector_size == 1 )); then return $sector_size; fi
                
                ((prev_alignment=alignment))

                # align next partition size
                ((alignment=$(align_ptn $alignment "$fstype" "$flags")))

                # realign existing partition size to next partition's 
                # filesystem alignment
                ((size=$(realign_size $(field "${partitions[i]}" $PALIGN_START) \
                                      $size $prev_alignment $alignment)))
            fi

            ((ptn_num=$(field "$ptn" $PPTN_NUM))) # extract partition number

            # add partition alignment to array in case partition needs to be
            # resized
            ((alignments[$ptn_num]=alignment))

            # add the newly aligned size as a last field to the existing
            # partition data
            partitions[i]+=$size

            # if swap, esp or bios, update the byte counter of non-resizable bytes
            [[ "$(field "$ptn" $PFSTYPE)" =~ swap || \
               "$(field "$ptn" $PFLAGS)" =~ esp   || \
               "$(field "$ptn" $PFLAGS)" =~ bios ]] && 
                ((no_resize_dst+=size))
        fi
    done

    local -i dst_postamble

    # get number of sectors to exclude from the end of the dst disk
    (( src_lba *= $(gdisk -l "$srcdisk" | grep "First usable sector is" | 
                                          cut -f 1 -d "," | cut -f 5 -d " ") ))

    # get total size of dst disk
    (( dst_disk_size = $(field "${disks_info[${OPTIONS[1]}]}" $DSIZE) ))

    # add dst postamble space to dst non-resizable space
    (( dst_space_avail = dst_disk_size - no_resize_dst ))
    (( dst_postamble = dst_space_avail - (dst_space_avail / DST_ALIGN) * DST_ALIGN ))
    (( dst_postamble < src_lba )) && (( dst_postamble = src_lba ))
    (( no_resize_dst += dst_postamble ))
    (( dst_space_avail -= dst_postamble ))

    # make sure that all partitions on src fit on dst
    if (( dst_disk_size - no_resize_dst <= 0 )); then
        cecho -e "\n${RED}Destination partition size ($YELLOW$dst_disk_size$RED)"\
                 "${RED}< source partition size ($YELLOW$no_resize_dst$RED)."\
                 "${RED}Exiting." | tee -a "$ERRFILE"
        return 1
    fi
    echo
}

# mask hibernation if it is unmasked
# return: 0 on success, 1 if parameter error else the error code of the command
#         that failed
mask_hibernation() {
    valid_opt_param "$1" # validate parameter
    
    # some other clone process has completed or was interrupted and sent signal
    # USR1 so that this process can handle masking/unmasking hibernation
    if (( $# == 1 )); then
        # sync and restore stdout and stderr to the terminal
        sync
        exec &> /dev/tty

        cecho -e "\n\nReceived signal USR1 from another clone process"\
                 "to mask/unmask hibernation..."
    fi  

    # init array, as 'hibernate' may be called below which adds elements to this 
    # array
    rsync_filters=() 

    local -i fd

    exec {fd}>>"$HBNFILE" # append to the hibernation lock file
    
    # critical section follows
    flock $fd >> "$LOGFILE" 2>> "$ERRFILE"
    local -i err=$?

    if (( ! err )); then
        local SEP="//"
        readonly SEP
        
        # mask/unmask hibernation if no other clone process already does
        if [[ ! -s "$HBNFILE" ]]; then
            local -a cmds

            hibernate cmds "mask" # add cmds to mask hibernation
            if (( ${#cmds[@]} )); then
                if (( $# == 1 )); then
                    cecho "Masking hibernation..."
                else
                    echo "Masking hibernation..."
                fi
                
                cmds+=("chmod go=+r $HBNFILE")
                exec_cmds "${cmds[@]}"
                ((err=$?))

                # add entry to hibernation lock file
                if (( ! err )); then
                    echo "$$_$OPTIONS_S" >&$fd
                    echo -n "$HBN_CFG_MNT_DIR $SEP " >&$fd
                    echo "${rsync_filters[$HBN_CFG_MNT_DIR]}" >&$fd
                fi
            fi
        else
            # if some other clone process is masking/unmasking hibernation then
            # hibernation files must be excluded from cloning
            local hbn_entry
            local mnt_dir
            local excludes
            
            hbn_entry=$(tail -1 "$HBNFILE")
            mnt_dir=$(expr "$hbn_entry" : "^\(.\+\) $SEP")
            excludes=$(expr "$hbn_entry" : "^.\+ $SEP \(.\+\)$")
            [[ ! "${rsync_filters[$mnt_dir]}" =~ $excludes ]] && 
                rsync_filters[$mnt_dir]+="$excludes"
        fi
                 
        flock -u $fd # release lock
    fi
    exec {fd}>&- # close hibernation lock file
    
    if (( $# == 1 )); then
        if (( err )); then
            cecho -e "${RED}Signal USR1 was handled unsuccessfully...\n"
            cleanup 1
        else
            cecho -e "${GREEN}Signal USR1 was handled successfully...\n"
        fi
    fi

    return $err
}

# calculate available disk space on dst and subtract any exlcuded dirs/files in
# case dst_size < src_size
# return: 0 on success else 1
calc_diskspace() {
    echo "Calculating available space on destination disk..."
    echo -e "\tTesting that source disk partitions have UUIDs..."

    local ptn
    local -i disk_num
    local fstype
    local -i ptn_num
    local flags    
    local srcmnt
    local -a mount_points=()
    local -i err

    # get mount points for src partitions
    for ptn in "${partitions[@]}"; do
        # extract disk number to find if partition is src or dst
        ((disk_num=$(field "$ptn" "$PDISK_NUM")))
        fstype=$(field "$ptn" "$PFSTYPE")           # extract filesystem type
        
        if (( disk_num == OPTIONS[0] )); then     # if is src partition
            ((ptn_num=$(field "$ptn" "$PPTN_NUM"))) # extract partition number
            flags=$(field "$ptn" "$PFLAGS")         # extract flags
            
            # mount all src partitions other than swap and bios_grub
            if [[ ! "$fstype" =~ swap && ! "$flags" =~ bios ]]; then
                mount_ptn "$srcdisk" $ptn_num srcmnt # mount src partition
                ((err=$?))
                if (( err )); then return $err; fi
                mount_points+=("$srcmnt")
                
                # return if any src partition does not have UUID
                flags=$(lsblk -no UUID "$srcdisk$SP$ptn_num" 2>> "$ERRFILE")
                if [[ -z "$flags" ]]; then
                    cecho -e "\n${RED}The $YELLOW$srcdisk$SP$ptn_num$RED source"\
                             "${RED}partition mounted on"\
                             "$YELLOW$(field "$srcmnt" "$MDIR")${RED} does not"\
                             "${RED}have a UUID. Exiting." | tee -a "$ERRFILE"
                    return 1
                fi
            fi
        fi
    done

    echo -e "\tGetting total data size on source disk..."
    
    # get the total data size on src
    src_ptn_data=()
    readarray -t src_ptn_data < <(df -ak --sync --output=source,used,pcent | grep "$srcdisk")

    local -i used
    local -i CONVERSION_UNIT=1024
    readonly CONVERSION_UNIT

    # add src bios partition
    if (( bios_ptn_nums[0] )); then
        (( used = $(lsblk -nb -o SIZE "$srcdisk$SP${bios_ptn_nums[0]}") / CONVERSION_UNIT ))
        src_ptn_data+=("$srcdisk$SP${bios_ptn_nums[0]} $used 0%")
    fi

    local i
    local -i src_data_size=0
    local source
    local pcent
    local -i total_pcent=0

    # save src partition data and calculate totals
    for i in "${!src_ptn_data[@]}"; do
        # remove whitespace
        src_ptn_data[i]=$(echo "${src_ptn_data[i]}" | xargs)
        source=$(field "${src_ptn_data[i]}" "$SOURCE" ' ')
        (( used = $(field "${src_ptn_data[i]}" "$USED" ' ') * CONVERSION_UNIT ))
        if [[ "$source" == "$srcdisk$SP${esp_ptn_nums[0]}" ]]; then
            pcent=0
        else
            pcent=$(field "${src_ptn_data[i]}" "$PCENT" ' ')
            pcent="${pcent/'%'}"
        fi
        src_ptn_data[i]="$source $used $pcent"
        (( total_pcent += pcent ))
        (( src_data_size += used ))
    done

    ((clone_size=src_data_size))

    # normalize percentages
    for i in "${!src_ptn_data[@]}"; do
        pcent=$(field "${src_ptn_data[i]}" "$PCENT" ' ')
        pcent=$(bc <<< "scale=5; $pcent / $total_pcent")
        src_ptn_data[i]="${src_ptn_data[i]%' '[0-9]*} $pcent"
    done

    echo -e "\tUnmounting any source partitions that were mounted..."

    # unmount src partitions that were mounted
    for ptn in "${mount_points[@]}"; do
        umount_ptn "$ptn"
        ((err=$?))
        if (( err )); then return $err; fi
    done

    echo -e "\n\tChecking files/directories excluded from source disk..."

    local -i fd
    local -a paths # the paths of an rsync filter
    local j
    local k
    local -a next_entries # files matching an rsync filter
    local srcptn
    local -A filters=() # key: rsync filter
                        # val: indices of array that stores rsync filter contents
    local -A user_filters=() # key: rsync filter
                             # val: user defined filter in $FILTERS file
    local -i match
    local -a entries=() # files matching all rsync filters
    local buf
    local -a abuf
    local MSG="Check the '$FILTERS' file"
    readonly MSG
    
    exec {fd}< "$FILTERS" # open filters file
    while read -r -u $fd; do
        # remove leading & trailing spaces and tabs
        REPLY=$(echo "$REPLY" | sed -e 's/^[[:blank:]]*//' -e 's/[[:blank:]]*$//')
        (( ! ${#REPLY} )) && continue       # ignore empty lines
        [[ "$REPLY" =~ ^#.*$ ]] && continue # ignore comments

        # split line into paths
        ((j=0))
        paths=()
        for (( i = 0; i < ${#REPLY}; ++i )); do
            if [[ "${REPLY:i:1}" != [[:blank:]] ]]; then
                # remove redundant '/' and '*'
                if [[ ("${REPLY:i:1}" != "*" && "${REPLY:i:1}" != "/") || \
                      "${REPLY:i:1}" != "${REPLY:i-1:1}" ]]; then
                    paths[j]+="${REPLY:i:1}"
                fi
            else
                if [[ "${paths[j]:${#paths[j]}-1:1}" == '\' ]]; then
                    paths[j]+="${REPLY:i:1}"
                else
                    ((++j))
                    while [[ "${REPLY:i:1}" == [[:blank:]] ]]; do ((++i)); done
                    ((--i))
                fi
            fi
        done

        buf="$CYAN'${paths[*]}'$YELLOW has wrong syntax and will be omitted. "
        buf+="$MSG for correct syntax."

        # For valid entries see '$FILTERS' file.
        case ${#paths[@]} in
            1) [[ ! "${paths[*]}" =~ ^[-+]/.+$ ]] && 
                   { cechot "$buf"; continue; }
            ;;            
            2) [[ ! "${paths[*]}" =~ ^[-+]/.*\ [^/].*$ ]] && 
                   { cechot "$buf"; continue; }
            ;;
            *) cechot "$buf"; continue ;;
        esac

        # Check if pathname is on src disk. 'paths' may include spaces so use
        # 'eval' to treat it as a single argument. Also, use 'dirname' in case
        # 'paths' includes a pattern that will expand to more than one entry.
        srcptn=$(eval \
                 df -ak --sync --output=source "$(dirname "${paths[0]:1}")" | tail -1)

        # skip files/dirs not on source disk. e.g. virtual file systems like
        # /sys, /proc, etc
        if [[ "${srcptn::1}" != "/" ]]; then
            if [[ ${paths[0]::1} == "+" ]]; then
                cechot "$CYAN'${paths[*]}'$YELLOW is not on the source disk"\
                       "and it's an include entry which is not valid. $MSG."
            elif [[ "$BOOTPTN" =~ $srcdisk$SP ]]; then
                add_filter filters user_filters paths
            else                
                cechot "$CYAN'${paths[*]}'$YELLOW exists but not on the source"\
                       "disk and will be omitted. $MSG."
            fi
            continue
        # if paths are not on src disk, skip them
        elif [[ ! "$srcptn" =~ $srcdisk$SP ]]; then
            cechot "$CYAN'${paths[*]}'$YELLOW exists but not on the source disk"\
                   "and will be omitted. $MSG."
            continue
        fi

        # get file(s) and/or directories
        if (( ${#paths[@]} == 2 )); then
            # iterate over relative path that will be tokenized based on '/' and
            # passed as a parameter to 'find' cmd
            ((j=0))
            for (( i = 0; i < ${#paths[1]}; ++i )); do
                if [[ "${paths[1]:$i:1}" == "/" ]]; then # get path up to '/'
                    if (( j )); then
                        get_entries next_entries "-type d"
                    else
                        # 'paths' may include spaces so use 'eval' to treat
                        # each path as a single argument
                        readarray -td '' next_entries < <(eval \
                                                          find "${paths[0]:1}" \
                                                               -name "${paths[1]:$j:$i-$j}" \
                                                               -type d \
                                                               -print0 2>> "$ERRFILE")
                    fi
                    (( ! ${#next_entries[@]} )) && break # break if no results                        
                    ((j=i+1))
                fi
            done
        
            # all tokens of path delimited by '/' were processed except last
            # token which is not delimited
            if (( j && j < i && ${#next_entries[@]} )); then
                get_entries next_entries
            elif (( ! j && i == ${#paths[1]} )); then
                # 'paths' may include spaces so use 'eval' to treat each path
                # as a single argument
                readarray -td '' next_entries < <(eval \
                                                  find "${paths[0]:1}" \
                                                       -name "${paths[1]}" \
                                                       -print0 2>> "$ERRFILE")
            fi
        else
            # 'paths' may include spaces so use 'eval' to treat each path as a
            # single argument
            readarray -td '' next_entries < <(eval \
                                              find "${paths[0]:1}" -maxdepth 0 \
                                                   -print0 2>> "$ERRFILE")
        fi
            
        # read next if file(s) and/or dir(s) don't exist
        if (( ! ${#next_entries[@]} )); then
            cechot "$CYAN'${paths[*]}'$YELLOW does not exist and will be omitted."\
                   "$MSG."
            continue
        fi

        # check if the filter has been processed already
        ((match=0))
        for k in "${!user_filters[@]}"; do
            # if new path is an existing filter, skip it
            if [[ "${paths[*]}" == "${user_filters["$k"]}" ]]; then
                cechot "$CYAN'${paths[*]}'$YELLOW is listed more than once"\
                        "and will be omitted. $MSG."
                ((match=1))
                break
            fi
            
            # compare exclude filters
            if [[ "${paths[0]::1}" == "-" && \
                    "${paths[0]::1}" == "${k::1}" ]]
            then
                # if existing filter "fits" into new filter, skip new
                if [[ "${user_filters["$k"]: -1}" == "/" && \
                        "${paths[*]}" =~ "${user_filters["$k"]}" ]]; then
                    cechot "$CYAN'${paths[*]}'$YELLOW is under"\
                            "$CYAN'${user_filters["$k"]}'$YELLOW and will be"\
                            "omitted. $MSG."
                    ((match=1))
                    break
                fi
                
                # if new filter is dir and "fits" into existing
                # filter, remove existing
                ((i=${#paths[@]}))
                if [[ "${paths[i-1]: -1}" == "/" && \
                        "${user_filters["$k"]}" =~ "${paths[*]}" ]]; then
                    cechot "$CYAN'${user_filters["$k"]}'$YELLOW is under"\
                            "$CYAN'${paths[*]}'$YELLOW and will be omitted. $MSG."
                    for i in ${filters["$k"]}; do # remove filter entries
                        unset entries[i]
                    done
                    
                    # remove rsync & user filters
                    unset filters["$k"] user_filters["$k"]
                fi                    
            fi
        done 
        (( match )) && continue

        for i in "${!next_entries[@]}"; do    
            # add a backslash to each directory
            [[ "${next_entries[i]: -1}" != "/" && -d "${next_entries[i]}" ]] &&
                next_entries[i]+="/"

            next_entries[i]="${paths[0]::1}${next_entries[i]}" # add the sign
        done

        ((j=${#next_entries[@]})) # get new offset for entries
        if (( j )); then
            if (( ${#entries[@]} )); then
                abuf=("${!entries[@]}") # get indices
                ((i=abuf[-1]+1)) # get next index of entries
            else
                ((i=0))
            fi
        
            buf=$(seq $i $((i+j-1)) | xargs)

            # add a space in the end so that all numbers are followed by it
            add_filter filters user_filters paths "$buf "

            entries+=("${next_entries[@]}") # add next entries to existing
        fi
    done
    exec {fd}<&- # close the filters file

    next_entries=() # release some memory

    local -A matched=() # key: [<filter_idx1>,<filter_idx2>]
                        # val: indices of matched entries
    local -i under

    for i in "${!entries[@]}"; do         # match entries
        [[ ! -v entries[i] ]] && continue # skip if unset
        
        ((match=0))
        for j in "${!entries[@]}"; do
            # check if an entry is under another
            if [[ "${entries[i]:1}" == "${entries[j]:1}" || \
                  ("${entries[j]: -1}" == "/" && \
                   "${entries[i]:1}" =~ "${entries[j]:1}") ]]
            then
                ((under=1))
            else
                ((under=0))
            fi
            
            # match entries that cancel out each other, i.e. include/exclude
            # entries
            if [[ "${entries[i]::1}" == '+' && "${entries[j]::1}" == '-' && \
                  $under -eq 1 ]]
            then
                [[ "${entries[i]:1}" == "${entries[j]:1}" ]] &&
                    add_match "$i" "$j" matched
                ((match=1))

            # match entries that are equal or under others, i.e.
            # include/include or exclude/exclude entries
            elif [[ (("${entries[i]::1}" == '+' && \
                      "${entries[j]::1}" == '+' && $j -ne $i) || \
                     ("${entries[i]::1}" == '-' && \
                      "${entries[j]::1}" == '-' && $j -ne $i)) && \
                    $under -eq 1 ]]
            then
                add_match "$i" "$j" matched
            fi
        done

        # in case include entry not matched by an exclude one, remove it
        if [[ "${entries[i]::1}" == '+' && $match -eq 0 ]]; then
            get_filter_data "$i" k j

            update_matched "$j" matched # update matched entries

            for j in ${filters["$k"]}; do # remove filter entries
                unset entries[j]
            done

            buf="$CYAN'${user_filters["$k"]}'$YELLOW is not under an "
            buf+="exclude entry and will be omitted. $MSG."               

            # remove rsync & user filters
            unset filters["$k"] user_filters["$k"]
            cechot "$buf"                
        fi
    done

    local sign

    # store matched filters, i.e. include and exclude filters that cancel out
    # each other, or filters that are equal or under others
    if (( ${#matched[@]} )); then
        local -A matched_processed=()
        local f
        local rm_entries
        local -A removed_entries
        local -a matched_filters
        local -A filters_rm=() # filters to remove

        # iterate over matched filters and store all that need to be removed
        for i in "${!matched[@]}"; do
            [[ -v matched_processed[$i] ]] && continue # skip already processed
            
            get_filter "${i/,+([0-9])}" k # get filter for 1st idx            
            get_filter "${i/+([0-9]),}" f # get filter for 2nd idx

            rm_entries="entries removed_entries"
            if [[ ${k::1} != "${f::1}" ]]; then # this is a tuple
                # set function to remove matched filter tuple entries
                rm_entries="rm_tuple_entries $rm_entries matched_filters"
            else # both filters are includes or excludes
                # set function to remove matched filter entries
                rm_entries="rm_filter_entries $rm_entries"
                buf=" is under "
            fi

            removed_entries=()
            matched_filters=()
            if $rm_entries; then # remove matched entries
                # set user message if both filters are includes or excludes
                [[ ${k::1} == "${f::1}" ]] &&
                    buf="$buf$CYAN'${user_filters["$f"]}'$YELLOW"
                ((match=1))
            else
                ((match=0))
            fi

            matched_processed[$i]= # add processed matched pair of indices
                        
            # find filters that match the filter with 1st idx
            sign="${f::1}"
            for j in "${!matched[@]}"; do
                # allow self only and different 2nd idx than the one used above
                (( ${j/,+([0-9])} != ${i/,+([0-9])} || \
                   ${j/+([0-9]),} == ${i/+([0-9]),} )) && 
                    continue
                                
                # get filter for 2nd idx
                get_filter "${j/+([0-9]),}" f

                # process filter with the same sign as the previous one
                [[ ${f::1} != "$sign" ]] && continue

                if $rm_entries; then # remove matched entries
                    # set user message if both filters are includes or excludes
                    if [[ ${k::1} == "${f::1}" ]]; then
                        if (( match )); then
                            buf+=" and $CYAN'${user_filters["$f"]}'$YELLOW"
                        else
                            buf="$buf$CYAN'${user_filters["$f"]}'$YELLOW"
                        fi
                    fi
                    ((match=1))
                fi

                matched_processed[$j]= # add processed matched pair of indices
            done

            # print matched filters and store them for removal
            if (( match )); then
                filters_rm[$k]= # store filter for removal
                if [[ ${k::1} != "$sign" ]]; then
                    # set user message
                    buf="$CYAN'${user_filters["$k"]}'$YELLOW"
                    for f in "${matched_filters[@]}"; do
                        buf+=" and $CYAN'${user_filters["$f"]}'$YELLOW"
                        filters_rm[$f]= # store filter for removal
                    done
                    cechot "$buf cancel out each other and will be omitted. $MSG."
                else
                    buf="$CYAN'${user_filters["$k"]}'$YELLOW$buf"
                    cechot "$buf and will be omitted. $MSG."
                fi
            fi                
        done

        # remove matched filters, i.e. include and exclude filters that cancel
        # out each other, or filters that are equal or under others
        for k in "${!filters_rm[@]}"; do 
            unset filters["$k"] user_filters["$k"] # remove rsync & user filters
        done        
    fi

    # reorder user filters storing the includes first
    abuf=()
    for buf in "${user_filters[@]}"; do
        if [[ "${buf::1}" == "+" ]]; then
            abuf=("${OFF}Include$YELLOW in cloning  : $CYAN${buf:1}" "${abuf[@]}")
        else
            abuf+=("Exclude from cloning: $CYAN${buf:1}")
        fi
    done
        
    # add mount points for removable media as an exclude entry
    if [[ "$BOOTPTN" =~ $srcdisk$SP ]]; then
        local MEDIA="-/media/*"
        readonly MEDIA

        filters[$MEDIA]=
        user_filters[$MEDIA]="$MEDIA"
        buf="Exclude from cloning: $CYAN${MEDIA:1}"
        buf+="$YELLOW (mount points for removable media)"
        abuf+=("$buf")    
    fi

    (( ${#abuf[@]} )) && echo
    for buf in "${abuf[@]}"; do # print reordered user filters
        cechot "$buf"
    done
    
    local -i exc_size
    local -i total_exc_size=0

    # calculate total size of excluded/included files/dirs
    for buf in "${entries[@]}"; do
        sign="${buf::1}"
        sign+="1"
        buf="${buf:1}"

        exc_size=$(du -sb "$buf" 2>> "$ERRFILE" | xargs 2>> "$ERRFILE" \
                                                | cut -f 1 -d ' ')
        ((exc_size*=-1*sign))
        if (( exc_size )); then
            ((total_exc_size+=exc_size))

            srcptn=$(df -ak --sync --output=source "$buf" 2>> "$ERRFILE" | tail -1)

            # remove the total size calculated above from the size of the
            # partiton the directory is on
            (( ! $? )) &&
                for i in "${!src_ptn_data[@]}"; do
                    source=$(field "${src_ptn_data[i]}" "$SOURCE" ' ')
                    if [[ "$source" == "$srcptn" ]]; then
                        (( used = $(field "${src_ptn_data[i]}" "$USED" ' ') - exc_size ))
                        pcent=$(field "${src_ptn_data[i]}" "$PCENT" ' ')
                        src_ptn_data[i]="$source $used $pcent"
                        break
                    fi
                done
        fi
    done

    ((clone_size-=total_exc_size))

    local -a sizes=("$src_data_size" "$total_exc_size" "$clone_size")
    sizes+=("$dst_disk_size")
    
    # convert sizes to appropriate units, e.g. GB, MB, etc.
    for i in "${!sizes[@]}"; do 
        convert_size sizes[i]
    done

    cecho -e "\n\tData size on source disk: ${OFF}${sizes[0]}$YELLOW."
    if (( total_exc_size )); then
        cechot "Data size of excluded directories and/or files on source disk:"\
               "${CYAN}${sizes[1]}$YELLOW."
        cechot "Total data size to be cloned from source disk:"\
               "$OFF${sizes[0]} - $CYAN${sizes[1]}$OFF = ${sizes[2]}$YELLOW."
    fi
    cechot "Total space on destination disk: $OFF${sizes[3]}$YELLOW."
    if (( clone_size > dst_disk_size )); then
        cechot "${RED}Data on source disk does not fit on destination disk"\
               "${RED}($YELLOW${sizes[2]} > ${sizes[3]}$RED). Exiting."\
            | tee -a "$ERRFILE"
        return 1
    else
        cechot "${GREEN}Data on source disk (${OFF}${sizes[2]}$GREEN) fits"\
               "${GREEN}on destination disk (${OFF}${sizes[3]}$GREEN). Proceeding..."
    fi
    echo

    # iterate over filters (first the include ones) and add them to the 
    # corresponding partition
    local srcmnt_dir

    for k in "${!filters[@]}"; do
        sign="${k::1}"
        k="${k:1}"

        # use 'dirname' in case 'k' includes a pattern that will expand to more
        # than one entry.        
        buf=$(dirname "$k")
        
        # get source partition for the filter
        while true; do
            # use 'eval' to treat filter as a single argument in case it
            # includes spaces
            srcptn=$(eval df -ak --sync --output=source "$buf" 2>> "$ERRFILE" | tail -1)
            if (( $? )); then
                if [[ "$buf" == "/" ]]; then
                    cecho "No souce partition found for '$k'. Exiting."\
                        | tee -a "$ERRFILE"
                    return 1
                else
                    buf=$(dirname "$buf" | tail -1)
                fi
            else
                break            
            fi
        done
        
        if [[ "${srcptn::1}" != "/" ]]; then
            srcmnt_dir="/" # located on root (/) partition                    
        else
            srcmnt_dir=$(lsblk -no MOUNTPOINT "$srcptn")
        fi

        k="${k//'"'/'\"'}" # escape double quotes
        
        # rsync uses the first filter it encounters to exclude/include
        # files/dirs therefore, the include filters must be first
        if [[ $sign == "+" ]]; then
            [[ "$k" =~ "/**/" ]] && 
                rsync_filters[$srcmnt_dir]="-f \"$sign ${k/'**/'}\" ${rsync_filters["$srcmnt_dir"]} "
            rsync_filters[$srcmnt_dir]="-f \"$sign $k\" ${rsync_filters["$srcmnt_dir"]} "
        else
            [[ "$k" =~ "/**/" ]] && 
                rsync_filters[$srcmnt_dir]+="-f \"$sign ${k/'**/'}\" "
            rsync_filters[$srcmnt_dir]+="-f \"$sign $k\" "
        fi
    done
}

# if necessary remove & create new partitions on dst
# return: 0 on success else the error code of the command that failed
create_partitions() {            
    echo "Checking partitions on destination disk..."
    echo -e "\tGetting source partition table type..."
    
    # extract src partition table type
    local ptn_tbl
    ptn_tbl=$(field "${disks_info[${OPTIONS[0]}]}" "$DPTN_TBL_TYPE")

    # if partition table on dst != src mark dst for wipe
    [[ "$ptn_tbl" != $(field "${disks_info[${OPTIONS[1]}]}" "$DPTN_TBL_TYPE") ]] && 
        ((create_ptn=1))

    local -a upartitions

    # get partitions to unmount on dst
    mapfile -t upartitions < <(findmnt -An -o source | grep "$dstdisk")
    
    local -a cmds # contains cmds to create partitions on dst
    local -i i

    # create cmds to unmount partitions on dst
    for i in "${!upartitions[@]}"; do
        cmds+=("umount '${upartitions[i]}'")
    done

    local -i SRC_DISK_SIZE
    SRC_DISK_SIZE=$(field "${disks_info[${OPTIONS[0]}]}" "$DSIZE")
    readonly SRC_DISK_SIZE
    local ptn
    local -i src_ptn_data_size=0
    local -i resize_for_data=0
    local -i disk_num
    local flags
    local fstype
    local -i bytes
    local -i SRC_DISK_RESIZE=SRC_DISK_SIZE-no_resize
    readonly SRC_DISK_RESIZE
    local -i dst_space_left=0
    
    if (( dst_disk_size < SRC_DISK_SIZE )); then
        # update clone size if dst partition size is based on src partition
        # data size
        for i in "${!src_ptn_data[@]}"; do
            ptn=$(field "${src_ptn_data[i]}" "$SOURCE" ' ')
            [[ "$ptn" == "$srcdisk$SP${esp_ptn_nums[0]}" || \
               "$ptn" == "$srcdisk$SP${bios_ptn_nums[0]}" ]] &&
                (( clone_size -= $(field "${src_ptn_data[i]}" "$USED" ' ') ))
        done

        # normally, the code within the for loop below should be within the loop
        # above but there's no guarantee that the ESP will be before any other 
        # partitions except the bios one
        for i in "${!src_ptn_data[@]}"; do
            if (( resize_for_data )); then
                break
            else
                # check if dst partition size is based on src partition data
                # size
                for ptn in "${partitions[@]}"; do
                    # extract disk number to find if partition is src or dst
                    ((disk_num=$(field "$ptn" "$PDISK_NUM")))

                    # if src partition
                    if (( disk_num == OPTIONS[0] )); then
                        flags=$(field "$ptn" "$PFLAGS")   # extract partition flags
                        fstype=$(field "$ptn" "$PFSTYPE") # extract filesystem type

                        # all partitions except esp, bios & swap can be resized
                        if [[ ! "$flags" =~ esp && ! "$flags" =~ bios && \
                              ! "$fstype" =~ swap ]]
                        then
                            get_ptn_size bytes # get ptn size in bytes variable

                            # get data size of src partition
                            ((src_ptn_data_size=$(field "${src_ptn_data[i]}" "$USED" ' ')))

                            # calculate space left on dst if dst partition size
                            # is based on src partition data size
                            if (( src_ptn_data_size > bytes )); then
                                (( dst_space_left = dst_space_avail - clone_size ))
                                (( resize_for_data = 1 ))
                                break
                            fi
                        fi
                    fi
                done
            fi
        done
    fi

    local flag
    local -i end
    local -i ptn_num
    local pct
    local cmd
    local -i j=0
    local dst_ptn
    local -a dst_ptns=()
    local -i alloc_bytes=0
    local -i ptn_tbl_flag=0
    local -i fd

    # iterate over all partitions to create commands that delete and create
    # partitions on dst if necessary
    for ptn in "${partitions[@]}"; do
        # extract disk number to find if partition src or dst
        ((disk_num=$(field "$ptn" "$PDISK_NUM")))
        ((ptn_num=$(field "$ptn" "$PPTN_NUM"))) # extract partition number
        fstype=$(field "$ptn" "$PFSTYPE")       # extract filesystem type
        
        # if src partition, create commands that:
        #     create new partition table
        #     create new partitions
        #     format new partitions
        if (( disk_num == OPTIONS[0] )); then
            name=$(field "$ptn" "$PNAME")           # extract partition name
            flags=$(field "$ptn" "$PFLAGS")         # extract partition flags
            ((ptn_cnt=$(field "$ptn" "$PPTN_CNT"))) # extract partition counter

            # all partitions except esp, bios & swap can be resized
            if [[ ! "$flags" =~ esp && ! "$flags" =~ bios && ! "$fstype" =~ swap ]]
            then
                # dst ptn size is calculated based on src ptn data size
                if (( resize_for_data )); then
                    ((src_ptn_data_size=0))
                    for i in "${!src_ptn_data[@]}"; do
                        if [[ "$(field "${src_ptn_data[i]}" "$SOURCE" ' ')" == \
                              "$srcdisk$SP$ptn_num" ]]
                        then
                            # get data size of src partition
                            ((src_ptn_data_size=$(field "${src_ptn_data[i]}" "$USED" ' ')))

                            # get the percentage of scr disk partition data
                            pct=$(field "${src_ptn_data[i]}" "$PCENT" ' ')

                            # calculate the bytes of the percentage above for
                            # space left on dst
                            cmd='{printf "%.0f", ($1 * $2 == int($1 * $2)) '
                            cmd+='? $1 * $2 : int($1 * $2) + 1}'
                            pct=$(awk "$cmd" <<< "$pct $dst_space_left")

                            # dst partition size = src partition data size +
                            #                      percentage of space left on dst
                            ((bytes=src_ptn_data_size+pct))
                            break
                        fi
                    done
                # dst ptn size is calculated based on percentage of src ptn size
                # with respect to src disk size
                else
                    get_ptn_size bytes # get ptn size in bytes variable
                fi

                # align partition size
                ((bytes=$(align_size $bytes "${alignments[$ptn_num]}")))

                # if next partition exists, align existing partition to next
                # partition's filesystem alignment
                if (( ptn_cnt < ${#alignments[@]} )); then
                    ((bytes=$(realign_size "$start" $bytes "${alignments[$ptn_num]}" \
                                           "${alignments[$((ptn_num+1))]}")))
                fi
            else
                # extract src partition size in bytes
                ((bytes=$(field "$ptn" "$PALIGN_SIZE")))
            fi

            # if partition is last one, check that it fits on remaining space
            (( ptn_cnt == ${#alignments[@]} )) &&
                while (( start + bytes - 1 > dst_disk_size - src_lba )); do
                    ((bytes-=alignments[$ptn_num]))
                done

            # update allocated space for dst disk
            (( resize_for_data )) && ((alloc_bytes+=bytes))

            ((end=start+bytes-1)) # set the end byte for the partition

            # create 'mktable' command (executed once only)
            if (( ! ptn_tbl_flag )); then
                cmds+=("wipefs --all --force '$dstdisk'")
                cmds+=("parted --script --fix '$dstdisk' mktable '$ptn_tbl'")
                ((ptn_tbl_flag=1))
            fi

            # create 'mkpart' command for new partition
            if (( ${#fstype} )); then
                cmd="parted --script --fix -a optimal '$dstdisk' unit $UNIT mkpart "
                cmd+="primary '$fstype' $start $end"
                cmds+=("$cmd")
            else
                cmd="parted --script --fix -a optimal '$dstdisk' unit $UNIT mkpart "
                cmd+="primary $start $end"
                cmds+=("$cmd")
            fi
            [[ "$name" && "$ptn_tbl" != "msdos" ]] && 
                cmds+=("parted --script --fix '$dstdisk' name $ptn_cnt '$name'")

            # check partition alignment
            cmds+=("parted --script --fix '$dstdisk' align-check opt $ptn_cnt")

            # create set commands to set partition flags
            ((i=1))
            flag=$(field "$flags" $i ',' | xargs)
            while (( ${#flag} )); do
                cmds+=("parted --script --fix '$dstdisk' set $ptn_cnt '$flag' on")
                ((++i))
                flag=$(field "$flags" $i ',' | xargs)
            done

            # create cmds to format the partition
            exec {fd}< "$FSTYPES" # open FSTYPES file
            # find filesystem command that applies to partition fstype
            while read -r -u $fd; do
                # remove leading and trailing whitespace
                REPLY=$(echo "$REPLY" | xargs 2>> "$ERRFILE")

                # ignore empty lines & comments
                (( ! ${#REPLY} )) || [[ "$REPLY" =~ ^#.*$ ]] && continue
                
                if [[ "$fstype" && "$REPLY" =~ $fstype ]]; then
                    # create command to format the newly created partition
                    cmds+=("$(field "$REPLY" 2) '$dstdisk$DP$ptn_cnt'")
                    break
                fi
            done
            exec {fd}<&- # close the FSTYPES file

            # compare src and dst partition data and if different set flag
            (( ! create_ptn )) &&
                if (( ${#dst_ptns[@]} > j )); then
                    flags=$(rm_lba_flag "$ptn_tbl" "$flags")
                    dst_ptn="$name$fstype$start$end$flags"
                    dst_ptn=$(echo "$dst_ptn" | xargs) # remove whitespace

                    [[ "$dst_ptn" != "${dst_ptns[j]}" ]] && ((create_ptn=1))
                    ((++j))
                else
                    ((create_ptn=1)) # src has more partitions than dst
                fi

            ((start=end+1)) # update start byte for next partition
        else
            # to remove swap partition it has to be off first
            [[ "$fstype" =~ swap ]] && 
            swapon | grep "$dstdisk$DP$ptn_num" > /dev/null 2>> "$ERRFILE" &&
                cmds+=("swapoff '$dstdisk$DP$ptn_num'")            

            # this is a dst partition therefore, create commands to delete it
            cmds+=("wipefs --all --force '$dstdisk$DP$ptn_num'")
            cmds+=("parted --script --fix '$dstdisk' rm $ptn_num")

            # add dst partition data to array to compare it with src partition
            # data (dst partitions are first in array)
            if (( ! create_ptn )); then
                flags=$(field "$ptn" "$PFLAGS")
                flags=$(rm_lba_flag "$ptn_tbl" "$flags")

                # get dst partition data as "$name$fstype$start$end$flags"
                dst_ptn=$(field "$ptn" "$PNAME")$(field "$ptn" "$PFSTYPE")
                dst_ptn+=$(field "$ptn" "$PSTART")$(field "$ptn" "$PEND")$flags
                dst_ptn=$(echo "$dst_ptn" | xargs) # remove whitespace
                dst_ptns+=("$dst_ptn")
            fi
        fi
    done

    # if src and dst partitions are different create dst partitions
    if (( create_ptn )); then
        echo -e "\n\tCreating partitions on destination disk..."
        exec_cmds "${cmds[@]}" # execute commands created above
    else
        echo
    fi
}

# find mount points for src and dst partitions and then clone files for each
# dst partition
# return: 0 on success, 1 if a function failed else the error code of the
#         command that failed
clone() {
    echo "Cloning..."
    echo -e "\tMounting partitions for source & destination disks if not mounted already..."

    local ptn
    local -i disk_num
    local fstype
    local flags
    local -i ptn_num
    local -i ptn_cnt
    local srcmnt
    local dstmnt
    local cmd
    local -a cmds=()
    local swap_ptn_UUIDs
    local -a swap_ptns_UUIDs=()
    local -i bios=0
    local -i err

    rsync_params=()
    
    # get mount points for src and dst partitions
    for ptn in "${partitions[@]}"; do
        # extract disk number to find if partition is src or dst
        ((disk_num=$(field "$ptn" "$PDISK_NUM")))
        if (( disk_num == OPTIONS[0] )); then # if is src partition
            fstype=$(field "$ptn" "$PFSTYPE")       # extract filesystem type
            flags=$(field "$ptn" "$PFLAGS")         # extract flags
            ((ptn_num=$(field "$ptn" "$PPTN_NUM"))) # extract partition number
            ((ptn_cnt=$(field "$ptn" "$PPTN_CNT"))) # extract partition counter

            # swap partitions are not cloned, just created, thus, are not part
            # of any rsync parameters and are not mounted
            if [[ "$fstype" =~ swap ]]; then
                # save src swap UUIDs, as they'll be replaced with dst ones
                # on dst disk after the cloning
                swap_ptn_UUIDs="$srcdisk$SP$ptn_num"
                swap_ptn_UUIDs+=":"
                
                # src swap UUID
                cmd="blkid $srcdisk$SP$ptn_num"
                swap_ptn_UUIDs+=$(expr "$($cmd)" : ".* UUID=\"\(.*\)\" TYPE")
                swap_ptn_UUIDs+=":"
                swap_ptn_UUIDs+="$dstdisk$DP$ptn_cnt"
                swap_ptn_UUIDs+=":"
                
                # dst swap UUID
                cmd="blkid $dstdisk$DP$ptn_cnt"
                swap_ptn_UUIDs+=$(expr "$($cmd)" : ".* UUID=\"\(.*\)\" TYPE")
                swap_ptns_UUIDs+=("$swap_ptn_UUIDs")
                cmds+=("mkswap -f '$dstdisk$DP$ptn_cnt'")
            elif [[ "$flags" =~ bios ]]; then
                ((bios=1)) # set flag if bios partition
            else
                mount_ptn "$srcdisk" "$ptn_num" srcmnt # mount src partition
                ((err=$?))
                if (( err )); then return $err; fi                
                mount_ptn "$dstdisk" "$ptn_cnt" dstmnt # mount dst partition
                ((err=$?))
                if (( err )); then return $err; fi                

                # pair src and dst mount points so that they can be used as src
                # and dst parameters in rsync
                rsync_params+=("$srcmnt$dstmnt")
            fi
        fi
    done

    echo -e "\tCreating list of system files and directories to exclude from cloning..."
    echo -e "\tCreating list of files created by clone script to exclude from cloning..."

    local srcptn
    local srcdir

    # log directory created by the script is excluded from cloning 
    srcptn=$(df -ak --sync --output=source "$(dirname "$LOGDIR")" | tail -1)
    srcdir=$(lsblk -no MOUNTPOINT "$srcptn")
    rsync_filters[$srcdir]+="-f \"- $(dirname "${LOGDIR//\"/\\\"}")/\" "

    local -a swap_entries
    local ptn_pair # src partition and its corresponding dst partition
    local swap_file
    local -a swap_file_cmds=()
    local -i size
    local dstdir

    if [[ "$BOOTPTN" =~ $srcdisk$SP ]]; then
        # find swap files listed in fstab file
        mapfile -t swap_entries < <(grep swap "$fstab_file")

        # find swap files that are active as some of these may not be listed in
        # fstab file
        mapfile -t -O ${#swap_entries[@]} swap_entries < <(swapon --noheadings | grep file)

        echo -e "\tCreating list of swap files, if any, to create on destination disk..."

        local -a swap_files=()
        local -i found
        local -i count

        # iterate over swap file names and add commands to create them on dst
        for swap_entry in "${swap_entries[@]}"; do
            # if swap entry is a file and not a partition
            if [[ "${swap_entry::1}" == "/" ]]; then
                swap_file="${swap_entry%%+( *)}" # get swap filename
                ((found=0))

                # check if swap file has been added to swap file list
                for added_swap_file in "${swap_files[@]}"; do
                    [[ "$added_swap_file" == "$swap_file" ]] && found=1 && break
                done
                (( found )) && continue    # swap file has been added so skip it
                swap_files+=("$swap_file") # add swap file to swap file list

                srcptn=$(df -ak --sync --output=source "$swap_file" | tail -1)

                # add the swap file only if it exists on the src disk
                if [[ "$srcptn" =~ $srcdisk$SP ]]; then
                    srcdir=$(lsblk -no MOUNTPOINT "$srcptn")
                    
                    # don't clone swap file (add to rsync filters)
                    rsync_filters[$srcdir]+="-f \"- ${swap_file//\"/\\\"}\" "
                    
                    if [[ -s "$swap_file" && -r "$swap_file" && -w "$swap_file" ]]
                    then
                        # add commands to create swap files on dst
                        ((size=$(find "$swap_file" -printf %s)))
                        
                        ((count=size/MIBIBYTE))

                        # get partition swap file resides on
                        ptn=$(df "$swap_file" | awk '/^\/dev/ {print $1}')
                        
                        for ptn_pair in "${rsync_params[@]}"; do
                            if [[ "$ptn" == "$(field "$ptn_pair" "$MPTN")" ]]; then
                                dstdir=$(field "$ptn_pair" $((MDIR+MDST)))

                                # the following three numbers at the beginning of 
                                # the command are parsed as follows:
                                # 1: run in the background
                                # 1: redirect stdout
                                # 0: don't redirect stderr
                                cmd="110 dd if=/dev/zero of='$dstdir'/'$swap_file' "
                                cmd+="bs=1M count=$count status=progress"
                                swap_file_cmds+=("$cmd")
                                swap_file_cmds+=("chmod 0600 '$dstdir'/'$swap_file'")
                                swap_file_cmds+=("mkswap -U clear '$dstdir'/'$swap_file'")
                                break
                            fi
                        done
                    fi
                fi
            fi
        done
    fi

    echo -e "\tCreating commands for cloning..."

    local key
    local -i used

    # iterate over partitions and create commands for cloning
    for ptn_pair in "${rsync_params[@]}"; do
        srcdir=$(field "$ptn_pair" "$MDIR") # get src dir

        if [[ "$srcdir" == "/" ]]; then
            key="$srcdir"
        else
            # remove trailing '/' as it's not part of key of associative array
            key="${srcdir::-1}"

            # remove src mount directory from filtered directories/files to
            # comply with rsync rules
            rsync_filters[$key]="${rsync_filters["$key"]//$key}"
        fi

        # get size of dst partition
        dstdir=$(field "$ptn_pair" $((MDIR+MDST)))

        if (( create_ptn )); then
            (( size = $(df -ak --block-size=KiB --sync --output=avail "$dstdir" \
                        2> "$ERRFILE" | tail -1 | tr -d [:alpha:]) ))
            (( size *= 1024 )) # convert to bytes

            # get size of src partition data
            for i in "${!src_ptn_data[@]}"; do
                srcptn=$(field "${src_ptn_data[i]}" "$SOURCE" ' ')
                [[ "$srcptn" == "$srcdisk$SP${esp_ptn_nums[0]}" || \
                   "$srcptn" == "$srcdisk$SP${bios_ptn_nums[0]}" ]] &&
                    continue

                if [[ "$srcptn" == $(field "$ptn_pair" "$MPTN") ]]; then
                    (( used = $(field "${src_ptn_data[i]}" "$USED" ' ') ))
                    break
                fi
            done

            # check if src partition data fits on dst partition size
            if (( size <= used )); then
                cecho -e "\n${RED}Destination partition"\
                         "$(field "$ptn_pair" "$((MPTN+MDST))")$RED mounted on"\
                         "$dstdir$RED is too small. It is $YELLOW$size KiB"\
                         "${RED}but should be $YELLOW> $used KiB$RED. Delete"\
                         "${RED}some data in source partition"\
                         "$YELLOW$(field "$ptn_pair" $((MPTN)))$RED mounted on"\
                         "$srcdir$RED. Exiting.\n"
                return 1
            fi
        fi

        flags="aAhHxlzEUtX"

        # After tests, rsync does not support extended attributes on HFS
        # filesystems so that option is removed below. After mounting an HFS
        # volume, executing a 'ls' command on the mounted volume produces the
        # following message "ls: '<mount_dir>': No data available" yet the
        # contents are displayed correctly.
        [[ "$(findmnt -no FSTYPE "$srcdir")" =~ hfs ]] && flags="${flags:0:-1}"

        # create clone command; the following two numbers at the beginning of the 
        # command are parsed as follows:
        # 1: run in the background
        # 0: don't redirect stdout
        cmds+=("10 rsync --log-file='$LOGFILE' --info=misc2,mount,name0,progress2,stats2 \
                         -$flags --numeric-ids --temp-dir=/tmp --delete-before \
                         --delete-excluded ${rsync_filters["$key"]} \
                         '$srcdir' '$dstdir'")
    done

    # add commands to create swap files, if any, on dst
    (( ${#swap_file_cmds[@]} )) && cmds+=("${swap_file_cmds[@]}")
    
    echo -e "\n\tRunning cloning commands (this may take a while)..."

    exec_cmds "${cmds[@]}" # execute commands created above
    ((err=$?))
    if (( err )); then return $err; fi

    # if src was used to boot the system make dst bootable as well
    if [[ "$BOOTPTN" =~ $srcdisk$SP ]]; then
        echo -e "\tCreating commands to make destination disk bootable..."
        echo -e "\tCreating command to update fstab file on destination disk..."

        cmds=()
        cmd="sed -i "
        
        # replace src partition data on dst fstab file for all partitions but swap
        for ptn_pair in "${rsync_params[@]}"; do
            # add sed command to replace src partition name with dst name
            cmd+="-e \"s|'$(field "$ptn_pair" "$MPTN")'|"
            cmd+="'$(field "$ptn_pair" $((MPTN+MDST)))'|g\" "

            # add sed command to replace src UUID with dst UUID
            cmd+="-e 's|$(field "$ptn_pair" "$MUUID")|"
            cmd+="$(field "$ptn_pair" $((MUUID+MDST)))|g' "
        done

        for swap_ptn_UUIDs in "${swap_ptns_UUIDs[@]}"; do
            # replace src partition data on dst fstab file for swap partition
            # add sed command to replace src partition name with dst name
            cmd+="-e 's|$(field "$swap_ptn_UUIDs" "$SPTN")|"
            cmd+="$(field "$swap_ptn_UUIDs" $((SPTN+SDST)))|g' "

            # add sed command to replace src UUID with dst UUID
            cmd+="-e 's|$(field "$swap_ptn_UUIDs" "$SUUID")|"
            cmd+="$(field "$swap_ptn_UUIDs" $((SUUID+SDST)))|g' "
        done
        
        # find location of dst fstab file
        fstab_file=$(dst_pathname "$fstab_file" "${rsync_params[@]}")
        if (( $? )); then
            stack "\nfstab file $YELLOW$fstab_file$RED not found! Exiting."
            return $?
        fi

        cmd+="'$fstab_file'"
        cmds+=("$cmd")

        local grubcfg_file="/grub/grub.cfg"

        # find location of dst grub.cfg file
        grubcfg_file=$(dst_pathname "$grubcfg_file" "${rsync_params[@]}")
        if (( $? )); then
            stack "\n$YELLOW$grubcfg_file$RED file not found! Exiting."
            return $?
        fi
        
        echo -e "\tCreating commands to update grub cfg file on destination disk..."

        local UUID
        
        # replace src partition data on dst grub.cfg file
        # iterate over all src partitions and find UUID which exists in grub.cfg
        cmd="sed -i "
        for ptn_pair in "${rsync_params[@]}"; do
            UUID=$(field "$ptn_pair" "$MUUID")
            if grep "$UUID" "$grubcfg_file" > /dev/null 2>> "$ERRFILE"; then
                # add sed command to replace src UUID with dst UUID
                cmd+="-e 's|$UUID|$(field "$ptn_pair" $((MUUID+MDST)))|g' "
            fi
        done
        
        echo -e "\tCreating commands to update grub default file on destination disk..."

        local grubdef_file="/etc/default/grub"

        # find location of dst default grub file
        grubdef_file=$(dst_pathname "$grubdef_file" "${rsync_params[@]}")
        if (( $? )); then
            stack "\n$YELLOW$grubdef_file$RED file not found! Exiting."
            return $?
        fi
        
        # if swap partitions exist update their UUID in the grub.cfg and grub
        # default files
        if (( ${#swap_ptns_UUIDs[@]} )); then
            local tmp=""
            for swap_ptn_UUIDs in "${swap_ptns_UUIDs[@]}"; do
                tmp+="-e 's|$(field "$swap_ptn_UUIDs" "$SUUID")|"
                tmp+="$(field "$swap_ptn_UUIDs" $((SUUID+SDST)))|g' "
            done
            cmds+=("$cmd$tmp '$grubcfg_file'")
            
            cmd="sed -i $tmp '$grubdef_file'"
        else
            cmd+="'$grubcfg_file'"        
        fi
        cmds+=("$cmd")

        local swap_file_UUID
        local -i swap_file_offset
        
        mapfile -t swap_entries < <(grep swap "$fstab_file")

        local STR_UUID="resume=UUID="
        local RE_SEARCH_UUID="${STR_UUID}[a-fA-F0-9-]\+"
        local STR_OFFSET="resume_offset="
        local RE_SEARCH_OFFSET="${STR_OFFSET}[0-9]\+"
        readonly STR_UUID RE_SEARCH_UUID STR_OFFSET RE_SEARCH_OFFSET

        for swap_entry in "${swap_entries[@]}"; do
            # if swap entry is a file and not a partition
            if [[ "${swap_entry::1}" == "/" ]]; then
                swap_file="${swap_entry%%+( *)}" # get swap filename
                swap_file="${swap_file:1}" # remove first char from swap filename

                # find location of dst swap file
                swap_file=$(dst_pathname "$swap_file" "${rsync_params[@]}")
                if (( $? )); then
                    stack "\nSwap file $YELLOW$swap_file$RED not found! Exiting."
                    return $?
                fi
                
                # get swap file UUID and offset
                swap_file_UUID=$(findmnt -no UUID -T "$swap_file")
                swap_file_offset=$(filefrag -v "$swap_file" | \
                                   awk '$1=="0:" {print substr($4, 1, length($4)-2)}')

                cmds+=("[[ '$swap_file_UUID' =~ ^[a-fA-F0-9][a-fA-F0-9-]+$ && \
                           '$swap_file_offset' =~ ^[0-9]+$ && \
                           '$swap_file_offset' -gt 0 ]]")
                      
                local REPLACE_UUID="$STR_UUID$swap_file_UUID"
                local REPLACE_OFFSET="$STR_OFFSET$swap_file_offset"
                readonly REPLACE_UUID REPLACE_OFFSET
                
                # replace UUID and offset with that of dst in grub cfg default file
                cmds+=("sed -i 's|$RE_SEARCH_UUID|$REPLACE_UUID|g' '$grubdef_file'")
                cmds+=("sed -i 's|$RE_SEARCH_OFFSET|$REPLACE_OFFSET|g' '$grubdef_file'")
                
                # replace UUID and offset with that of dst in grub cfg file
                cmds+=("sed -i 's|$RE_SEARCH_UUID|$REPLACE_UUID|g' '$grubcfg_file'")
                cmds+=("sed -i 's|$RE_SEARCH_OFFSET|$REPLACE_OFFSET|g' '$grubcfg_file'")
            fi
        done

        local -a dstinfo
        
        # get dst info
        mapfile -d ' ' -t dstinfo < <(lsblk -nr --nodeps --output NAME,TRAN,RM | 
                                        grep "${dstdisk//\/dev\/}")

        # find if dst is removable disk
        local -i removable=0
        [[ "${dstinfo[1]}" == usb || "${dstinfo[2]}" -eq 1 ]] && 
            ((removable=1))

        local dstptn
        local buf                    
        local -a entries
        local entry
        local distro
        local SHIM="[Ss][Hh][Ii][Mm]"
        readonly SHIM

        for ptn_pair in "${rsync_params[@]}"; do
            dstptn=$(field "$ptn_pair" $((MPTN+MDST)))

            # if boot partition and bios flag is set, install grub on bios
            # partition
            if [[ "$dstptn" == "$dstdisk$DP${boot_ptn_nums[1]}" && $bios -eq 1 ]]
            then
                echo -e "\tCreating command to install grub on bios "\
                        "partition on destination disk..."
                
                # the following three numbers at the beginning of the command
                # are parsed as follows:
                # 1: run in the background
                # 1: redirect stdout
                # 0: don't redirect stderr
                dstdir=$(field "$ptn_pair" $((MDIR+MDST)))
                cmds+=("110 grub-install --target=i386-pc \
                                         --boot-directory='$dstdir' \
                                         --recheck '$dstdisk'")
            fi
            
            # if esp partition and UEFI boot is enabled, install UEFI boot
            # entries if required
            if [[ "$dstptn" == "$dstdisk$DP${esp_ptn_nums[1]}" ]]; then
                buf=$(efibootmgr 2> "$ERRFILE")
                ((err=$?))
                if (( ! err && ! removable )); then
                    echo
                    # get dst boot partition UUID
                    UUID=$(field "$ptn_pair" $((MUUID+MDST)))

                    # get dst boot partition UUID entry
                    UUID=$(lsblk -nro +UUID,PARTUUID | grep "$UUID")
                    UUID="${UUID//+(* )}" # extract partition UUID
                    
                    # get boot entries (they contain 'EFI' string)
                    mapfile -t entries < <(find "$BOOTDIR"/$EFI -name "*.$EFI")

                    for entry in "${entries[@]}"; do
                        entry="${entry#"$BOOTDIR"}" # remove bootdir
                        
                        # skip entries that contain '/BOOT/' (it's for
                        # removable media) or not 'shim'
                        [[ "$entry" =~ /[Bb][Oo]{2,2}[Tt]/ && ! "$entry" =~ $SHIM ]] && 
                            continue

                        # remove suffix up to and including last '/'
                        distro="${entry%+(/*)}"
                        
                        # remove prefix up to and including last '/'
                        distro="${distro##+(*/)}"

                        # if no shim boot entries for dst, add them
                        entry="${entry//'/'/'\'}"
                        if [[ ! "$buf" =~ .+${esp_ptn_nums[1]}.+$UUID.+"$entry" ]]
                        then
                            echo -e "\tCreating command to add UEFI" \
                                    "boot entry '$entry' ..."
                            cmds+=("efibootmgr --create --disk '$dstdisk' \
                                                --loader '$entry' \
                                                --label 'Shim-$distro' \
                                                --part ${esp_ptn_nums[1]} \
                                                --unicode")
                        fi
                    done
                fi
            fi
        done
        
        exec_cmds "${cmds[@]}" # execute commands created above
    fi
}

# $1:   : int, optional, valid value: 1, cancellation signal was received
# return: 0 on success, 1 if parameter error else the error code of the command
#         that failed
cleanup() {
    local -i sig=$? # the received signal is equal to sig+128

    valid_opt_param "$1" # validate parameter
    
    local -i err=0
    local -a cmds

    # if cancellation signal was received
    if (( $# == 1 )); then
        # if user canceled while waiting for input in the read function or
        # while rsync was running, the received signal is < SIGMASK
        (( sig < SIGMASK )) && ((sig=SIGMASK+2)) # set it to SIGINT

        local signame

        ((sig-=SIGMASK))
        case $sig in
            [1-9]*) signame=" $sig) " ;;
            [10-64]*) signame="$sig) " ;; # max sig is 64
        esac
        
        signame=$(expr "$(kill -l | grep "$signame")" : "^.*$signame\([A-Z]\+\)")
        
        cecho -e "\n\nReceived signal '$signame'. Please let cleanup finish."\
                 "\nCleanup in progress..."

        # pids of processes running in background
        local -a pids
        mapfile -t pids < <(jobs -p)
    
        if (( ${#pids[@]} )); then # kill processes running in background
            echo -e "\tKilling jobs running in the background..."
            
            # create command to terminate any processes running in background
            # the following three numbers at beginning of command are parsed as
            # follows:
            # 0: don't run in the background
            # 0: don't redirect stdout
            # 0: don't redirect stderr
            cmds=("000 kill -s TERM ${pids[*]} >> '$LOGFILE' 2>> '$ERRFILE' || true")
            exec_cmds "${cmds[@]}"
            ((err=$?))
        fi
    else
        echo "Cleaning up..."
    fi

    local -i tmp
    
    if grep ^$$ "$LCKFILE" &> /dev/null; then
        echo -e "\tIgnoring cancellation signals during cleanup..."

        # while cleanup is running it should not be interrupted by a cancel signal
        cmds=("trap '' $CANCEL_SIGNALS")
        exec_cmds "${cmds[@]}"
        ((err=$?))

        echo -e "\tUnmounting partitions on source and/or destination disks that"\
                "were mounted, if any..."

        local ptn_pair

        # unmount partitions that were mounted
        for ptn_pair in "${rsync_params[@]}"; do
            umount_ptn "$ptn_pair"
            ((tmp=$?))
            (( ! err )) && ((err=tmp))
        done

        rsync_params=()
        
        unmask_hibernation
        ((tmp=$?))
        (( ! err )) && ((err=tmp))
        
        echo -e "\tReseting signal(s) and remove the entry of this clone process" \
                "from the lock file..."

        cmds=("trap - USR1 $CANCEL_SIGNALS")
        cmds+=("flock '$LCKFILE' sed -Ezi 's|$$_${OPTIONS_S}[[:space:]]+||g' '$LCKFILE'")
        exec_cmds "${cmds[@]}"
    elif [[ "$OPTIONS_S" && "$CMDFILE" =~ $OPTIONS_S ]]; then
        echo -e "\tReseting signal(s)..."

        cmds=("trap - USR1 $CANCEL_SIGNALS")
        exec_cmds "${cmds[@]}"
    # if script was cancelled during usage message skip most of cleanup
    else
        trap - USR1 $CANCEL_SIGNALS &> /dev/null # reset all signals
    fi
    ((tmp=$?))
    (( ! err )) && ((err=tmp))
    
    if (( $# == 1 )); then # if cancellation signal was received
        local buf="$YELLOW${REDB}Cloning was canceled.$OFF "
        
        if (( err )); then
            result "$buf${RED}Cleanup was unsuccessful."
        else
            result "$buf${GREEN}Cleanup completed successfully."
        fi
        ((tmp=$?))
        if (( ! err )); then exit $tmp; else exit $err; fi
    fi

    return $err
}

# called just before the script terminates printing the clone result and run time
# $1: str, optional, a message to print
result() {
    local -i err=0

    if [[ "$OPTIONS_S" && "$CMDFILE" =~ $OPTIONS_S ]]; then
        # get number of clone script instances
        if get_pids; then
            # if this is the only clone process then pid & hibernation lock
            # files can be safely removed
            echo -e "\tDeleting lock files directory $LCKDIR ..."

            declare -a cmds=()

            cmds+=("rm -rf '$LCKDIR'")
            exec_cmds "${cmds[@]}"
            ((err=$?))
        fi
    fi

    (( ${#1} )) && cecho -e "$1"
    
    if [[ "$START_DATE" ]]; then
        # the timestamp will be used to calculate the clone run time
        local end_date
        end_date=$(date)
        local -i runtime
        ((runtime=$(date -d "$end_date" +%s)-$(date -d "$START_DATE" +%s)))
        local -i seconds=runtime%60
        local -i hours=runtime/$((60*60))
        local -i minutes=$((runtime-(hours*60*60)))/60
        local label="Duration"

        cprintf "%-${#label}s: %s\n%-${#label}s: %s\n%s: %02dh:%02dm:%02ds\n"\
                "Start" "$START_DATE" "End" "$end_date" "$label" $hours $minutes $seconds
    else
        echo
    fi

    return $err
}

declare -i err=0

source "$SCRIPTDIR"/base_functions.sh && trap_signals
