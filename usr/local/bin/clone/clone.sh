        mask_hibernation  && 
        calc_diskspace    && # check if src fits on dst
        create_partitions && # create partitions on dst if different on src
        clone
        ((err=$?))
    done
cleanup
((err+=$?))

if (( ! err )); then
    result "${GREEN}Cloning completed successfully."
else
    result "${RED}Cloning was unsuccessful."
fi
((err+=$?))

exit $err
